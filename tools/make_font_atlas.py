"""Generates source/Cutup/FontAtlas.h: a signed-distance-field atlas for the fonts in fonts/.
SDF text stays crisp at any size on the GPU. Run: python tools/make_font_atlas.py"""
import os, numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.ndimage import distance_transform_edt
from fontTools.ttLib import TTFont
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
FONTS = ['ArchivoBlack-Regular.ttf', 'Anton-Regular.ttf']
CHARS = [chr(c) for c in range(32, 127)] + list('ČćĆčŽžŠšĐđÀÁÂÄÅÇÈÉÊËÌÍÎÏÑÒÓÔÕÖØÙÚÛÜÝàáâäåçèéêëìíîïñòóôõöøùúûüýÿßŁłŃńŚśŹźŻżĄąĘęŒœ€…–—’“”„')
HI = 192          # render size
SCALE = 4         # downsample factor -> 48 px em in the atlas
SPREAD = 24       # SDF spread in hi-res px (=6 px in atlas)
PAD = SPREAD + 4
W = 1024
glyphs = []       # (font, cp, img, metrics)
for fi, fname in enumerate(FONTS):
    path = os.path.join(ROOT, 'fonts', fname)
    cmap = TTFont(path).getBestCmap()
    font = ImageFont.truetype(path, HI)
    asc, desc = font.getmetrics()
    for ch in CHARS:
        if ord(ch) not in cmap: continue
        adv = font.getlength(ch)
        l, t, r, b = font.getbbox(ch, anchor='ls')
        if ch == ' ' or r <= l:
            glyphs.append((fi, ord(ch), None, (adv / HI, 0, 0, 0, 0))); continue
        w, h = r - l + 2 * PAD, b - t + 2 * PAD
        w += (-w) % SCALE; h += (-h) % SCALE
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((PAD - l, PAD - t), ch, font=font, fill=255, anchor='ls')
        a = np.asarray(im) > 127
        d = distance_transform_edt(~a) - distance_transform_edt(a)        # >0 outside
        sdf = np.clip(0.5 - d / (2 * SPREAD), 0, 1)                          # 0.5 = edge
        small = Image.fromarray((sdf * 255).astype(np.uint8)).resize((w // SCALE, h // SCALE), Image.LANCZOS)
        # plane bounds in em units (relative to baseline, y up)
        pl = (l - PAD) / HI; pr = (l - PAD + w) / HI; pt = -(t - PAD) / HI; pb = -(t - PAD + h) / HI
        glyphs.append((fi, ord(ch), small, (adv / HI, pl, pb, pr, pt)))
# shelf pack
x = y = rowh = 0; place = []
for g in glyphs:
    im = g[2]
    if im is None: place.append(None); continue
    if x + im.width > W: x = 0; y += rowh + 1; rowh = 0
    place.append((x, y)); x += im.width + 1; rowh = max(rowh, im.height)
H = y + rowh; H += (-H) % 4
atlas = np.zeros((H, W), np.uint8)
for g, p in zip(glyphs, place):
    if p: atlas[p[1]:p[1] + g[2].height, p[0]:p[0] + g[2].width] = np.asarray(g[2])
Image.fromarray(atlas).save(os.path.join(HERE, 'font_atlas_preview.png'))
out = ['// Generated by tools/make_font_atlas.py - do not edit.',
       '// Fonts: ' + ', '.join(FONTS) + ' (SIL Open Font License, see fonts/).', '#pragma once', '',
       'namespace cutup {', 'struct Glyph { unsigned short font; unsigned int cp; float advance, pl, pb, pr, pt, u0, v0, u1, v1; };',
       f'static const int kAtlasW = {W}, kAtlasH = {H}, kFontCount = {len(FONTS)};',
       f'static const char* const kFontNames[ {len(FONTS)} ] = {{ ' + ', '.join('"%s"' % f.split("-")[0].replace("ArchivoBlack", "Archivo Black") for f in FONTS) + ' };',
       f'static const Glyph kGlyphs[ {len(glyphs)} ] = {{']
for g, p in zip(glyphs, place):
    adv, pl, pb, pr, pt = g[3]
    if p: u0, v0, u1, v1 = p[0] / W, p[1] / H, (p[0] + g[2].width) / W, (p[1] + g[2].height) / H
    else: u0 = v0 = u1 = v1 = 0
    out.append(f'\t{{ {g[0]}, {g[1]}u, {adv:.5f}f, {pl:.5f}f, {pb:.5f}f, {pr:.5f}f, {pt:.5f}f, {u0:.6f}f, {v0:.6f}f, {u1:.6f}f, {v1:.6f}f }},')
out.append('};'); out.append(f'static const int kGlyphCount = {len(glyphs)};')
out.append(f'static const unsigned char kAtlas[ {W * H} ] = {{')
flat = atlas.flatten()
for i in range(0, len(flat), 64): out.append(','.join(map(str, flat[i:i + 64])) + ',')
out.append('};'); out.append('}//namespace cutup'); out.append('')
open(os.path.join(ROOT, 'source', 'Cutup', 'FontAtlas.h'), 'w').write('\n'.join(out))
print(len(glyphs), 'glyphs, atlas', W, 'x', H)
